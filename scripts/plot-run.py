# plot-run.py -- draw a PNG chart of a run CSV using Pillow (no matplotlib needed).
# Two panels: top = PV/SV temperature, bottom = MV output.
# ASCII labels so the default font renders cleanly.
import csv, os, sys
from PIL import Image, ImageDraw, ImageFont

def load(path):
    rows = []
    with open(path, 'r', encoding='utf-8-sig', newline='') as f:
        lines = [ln.strip() for ln in f if ln.strip()]
    header = lines[0].split(',')
    for ln in lines[1:]:
        parts = ln.split(',')
        while len(parts) > len(header):
            parts = [parts[0] + parts[1]] + parts[2:]
        r = dict(zip(header, parts))
        try:
            rows.append((float(r.get('elapsed_s', 0)), float(r.get('PV_C', 0)),
                         float(r['SV_C']) if r.get('SV_C') else None,
                         float(r['MV_pct']) if r.get('MV_pct') else 0.0))
        except Exception:
            pass
    return rows

W, H = 1600, 1000
ML, MR, MT = 110, 60, 90
TOP_H = 620
BOT_TOP = MT + TOP_H + 90
BOT_H = 180
FONT = 'C:/Windows/Fonts/arial.ttf'
def f(sz):
    try:
        return ImageFont.truetype(FONT, sz)
    except Exception:
        return ImageFont.load_default()

def main():
    src = sys.argv[1]
    out = os.path.splitext(src)[0] + '.png'
    rows = load(src)
    if not rows:
        print('no data'); return
    t0 = rows[0][0]; t1 = rows[-1][0]
    pvs = [r[1] for r in rows]
    svs = [r[2] for r in rows if r[2] is not None]
    mvs = [r[3] for r in rows]
    ymin = min(min(pvs), 20.0); ymax = max(max(pvs), (max(svs) if svs else 0)) + 20
    img = Image.new('RGB', (W, H), 'white')
    d = ImageDraw.Draw(img)
    # titles
    d.text((ML, 30), 'Run: ' + os.path.basename(src), fill='black', font=f(26))
    d.text((ML, 62), 'PV (red) / SV (blue)  |  bottom: MV percent (green)   peak=%.1f  overshoot=%.1f' % (max(pvs), max(pvs) - (max(svs) if svs else max(pvs))), fill='#444444', font=f(16))
    # ---------- top panel ----------
    x0, x1 = ML, W - MR
    y0, y1 = MT, MT + TOP_H
    def px(t): return x0 + (t - t0) / (t1 - t0) * (x1 - x0)
    def py(v): return y1 - (v - ymin) / (ymax - ymin) * (y1 - y0)
    d.rectangle([x0, y0, x1, y1], outline='black')
    # grid
    for i in range(0, 11):
        v = ymin + (ymax - ymin) * i / 10
        yy = py(v)
        d.line([x0, yy, x1, yy], fill='#e0e0e0')
        d.text((x0 - 70, yy - 8), '%.0f' % v, fill='#333333', font=f(14))
    for i in range(0, 13):
        t = t0 + (t1 - t0) * i / 12
        xx = px(t)
        d.line([xx, y0, xx, y1], fill='#f0f0f0')
        d.text((xx - 18, y1 + 8), '%.0f' % t, fill='#333333', font=f(14))
    d.text((x0 - 70, y0 - 26), 'C', fill='black', font=f(16))
    d.text((x1 - 20, y1 + 34), 'time (s)', fill='black', font=f(16))
    # target line
    if svs:
        tgt = max(svs)
        d.line([x0, py(tgt), x1, py(tgt)], fill='#bbbbbb')
        d.text((x1 - 120, py(tgt) - 18), 'target %.0f' % tgt, fill='#888888', font=f(14))
    # curves
    pts_pv = [(px(r[0]), py(r[1])) for r in rows]
    if len(pts_pv) > 1: d.line(pts_pv, fill='#d62728', width=3)
    pts_sv = [(px(r[0]), py(r[2])) for r in rows if r[2] is not None]
    if len(pts_sv) > 1: d.line(pts_sv, fill='#1f77b4', width=2)
    # ---------- bottom panel ----------
    bx0, bx1 = x0, x1
    by0, by1 = BOT_TOP, BOT_TOP + BOT_H
    def bpy(v): return by1 - v / 60.0 * (by1 - by0)
    d.rectangle([bx0, by0, bx1, by1], outline='black')
    for i in range(0, 7):
        v = 60 * i / 6
        yy = bpy(v)
        d.line([bx0, yy, bx1, yy], fill='#e0e0e0')
        d.text((bx0 - 55, yy - 8), '%.0f' % v, fill='#333333', font=f(14))
    d.text((bx0 - 70, by0 - 24), 'MV %', fill='black', font=f(16))
    pts_mv = [(px(r[0]), bpy(min(60, max(0, r[3])))) for r in rows]
    if len(pts_mv) > 1: d.line(pts_mv, fill='#2ca02c', width=2)
    # legend
    lx, ly = x1 - 260, y0 + 14
    for i, (lab, col) in enumerate([('PV', '#d62728'), ('SV', '#1f77b4'), ('MV', '#2ca02c')]):
        d.line([lx, ly + i*24, lx + 36, ly + i*24], fill=col, width=4)
        d.text((lx + 44, ly + i*24 - 9), lab, fill='black', font=f(16))
    d.text((ML, H - 40), 'generated by plot-run.py', fill='#999999', font=f(13))
    img.save(out)
    print('saved: ' + out)

main()
